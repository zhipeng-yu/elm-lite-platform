DROP TABLE IF EXISTS points_order_allocation;
DROP TABLE IF EXISTS points_order_spend;
DROP TABLE IF EXISTS points_grant;

CREATE TABLE points_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    source_type VARCHAR(16) NOT NULL,
    event_key VARCHAR(64) NOT NULL,
    basis_units BIGINT NOT NULL,
    awarded_points BIGINT NOT NULL,
    remaining_points BIGINT NOT NULL,
    earned_on DATE NOT NULL,
    expires_on DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, source_type, event_key),
    CHECK (remaining_points >= 0 AND remaining_points <= awarded_points),
    CHECK (expires_on > earned_on)
);
CREATE TABLE points_order_spend (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
    points BIGINT NOT NULL CHECK (points > 0),
    status VARCHAR(16) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE points_order_allocation (
    spend_id BIGINT NOT NULL REFERENCES points_order_spend(id),
    grant_id BIGINT NOT NULL REFERENCES points_grant(id),
    points BIGINT NOT NULL CHECK (points > 0),
    PRIMARY KEY (spend_id, grant_id)
);
