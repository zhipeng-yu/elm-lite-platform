CREATE TABLE points_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    source_type VARCHAR(16) NOT NULL,
    event_key VARCHAR(64) NOT NULL,
    basis_units BIGINT NOT NULL CHECK (basis_units >= 0),
    awarded_points BIGINT NOT NULL CHECK (awarded_points >= 0),
    remaining_points BIGINT NOT NULL CHECK (remaining_points >= 0 AND remaining_points <= awarded_points),
    earned_on DATE NOT NULL,
    expires_on DATE NOT NULL CHECK (expires_on > earned_on),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_points_grant_event UNIQUE (user_id, source_type, event_key),
    CONSTRAINT fk_points_grant_user FOREIGN KEY (user_id) REFERENCES users (id)
);
