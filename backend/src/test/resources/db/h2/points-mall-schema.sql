CREATE TABLE points_mall_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    points_cost BIGINT NOT NULL CHECK(points_cost > 0),
    stock INT NOT NULL CHECK(stock >= 0),
    enabled TINYINT NOT NULL CHECK(enabled IN(0,1))
);
CREATE TABLE points_mall_redemption (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    item_id BIGINT NOT NULL REFERENCES points_mall_item(id),
    item_name VARCHAR(100) NOT NULL,
    quantity INT NOT NULL CHECK(quantity > 0),
    points_per_item BIGINT NOT NULL CHECK(points_per_item > 0),
    total_points BIGINT NOT NULL CHECK(total_points > 0),
    request_key VARCHAR(64) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    UNIQUE(user_id,request_key)
);
CREATE TABLE points_mall_allocation (
    redemption_id BIGINT NOT NULL REFERENCES points_mall_redemption(id),
    grant_id BIGINT NOT NULL REFERENCES points_grant(id),
    points BIGINT NOT NULL CHECK(points > 0),
    PRIMARY KEY(redemption_id,grant_id)
);
