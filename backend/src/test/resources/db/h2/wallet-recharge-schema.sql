DROP TABLE IF EXISTS wallet_transaction;
DROP TABLE IF EXISTS wallet_recharge_rule;
DROP TABLE IF EXISTS virtual_wallet;

CREATE TABLE virtual_wallet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_type VARCHAR(16) NOT NULL,
    owner_id BIGINT NOT NULL,
    balance_cent BIGINT NOT NULL DEFAULT 0,
    frozen_balance_cent BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT NULL,
    CONSTRAINT uk_recharge_wallet_owner UNIQUE (owner_type, owner_id)
);

CREATE TABLE wallet_recharge_rule (
    id BIGINT PRIMARY KEY,
    threshold_cent BIGINT NOT NULL,
    reward_cent BIGINT NOT NULL,
    enabled TINYINT NOT NULL,
    updated_at TIMESTAMP DEFAULT NULL
);

CREATE TABLE wallet_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_no VARCHAR(36) NOT NULL UNIQUE,
    transaction_type VARCHAR(16) NOT NULL,
    request_wallet_id BIGINT NOT NULL,
    request_key VARCHAR(64) NOT NULL,
    source_wallet_id BIGINT,
    destination_wallet_id BIGINT,
    amount_cent BIGINT NOT NULL,
    reward_cent BIGINT NOT NULL DEFAULT 0,
    fee_cent BIGINT NOT NULL DEFAULT 0,
    source_balance_after_cent BIGINT,
    destination_balance_after_cent BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_recharge_request UNIQUE (request_wallet_id, request_key),
    CONSTRAINT fk_recharge_request_wallet FOREIGN KEY (request_wallet_id) REFERENCES virtual_wallet(id),
    CONSTRAINT fk_recharge_source_wallet FOREIGN KEY (source_wallet_id) REFERENCES virtual_wallet(id),
    CONSTRAINT fk_recharge_dest_wallet FOREIGN KEY (destination_wallet_id) REFERENCES virtual_wallet(id),
    CONSTRAINT chk_recharge_test_failure CHECK (request_key <> 'FAIL_LEDGER')
);

