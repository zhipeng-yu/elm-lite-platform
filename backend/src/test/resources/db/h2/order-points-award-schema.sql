DROP TABLE IF EXISTS points_grant;
DROP TABLE IF EXISTS points_rule;
CREATE TABLE points_rule (
    source_type VARCHAR(16) PRIMARY KEY,
    units_per_award BIGINT NOT NULL,
    points_per_award BIGINT NOT NULL,
    valid_days INT NOT NULL,
    enabled TINYINT NOT NULL
);
INSERT INTO points_rule VALUES ('ORDER', 100, 1, 365, 1);
CREATE TABLE points_grant (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    source_type VARCHAR(16) NOT NULL,
    event_key VARCHAR(64) NOT NULL,
    basis_units BIGINT NOT NULL,
    awarded_points BIGINT NOT NULL,
    remaining_points BIGINT NOT NULL,
    earned_on DATE NOT NULL,
    expires_on DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(user_id, source_type, event_key)
);
